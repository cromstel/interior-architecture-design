/**
 * Dev-time generator for the intrinsic width of every image, by public path.
 *
 * `srcSetFor` emits width descriptors, and a descriptor has to equal the file's
 * true pixel width or the browser mis-selects candidates.
 *
 * This started out recording only the `-lg` tier, because that tier has no
 * single width: `shrink-oversized-avif.mjs` caps any AVIF over 400 KB at 2000px
 * while the rest stay at 2400px, and a hardcoded `2000w` was wrong for 13 of 19
 * files. The small and base tiers were assumed to be fixed by convention.
 *
 * That assumption stopped holding. The three founder portraits are now cropped
 * square, and a square crop can only be as large as its source is tall — Claire
 * citgroup's source is 1200x798, so her square is 798x798 and her base tier is no
 * longer 1200w. The other 79 base assets are still exactly 1200px and all 81
 * `-sm` assets exactly 800px, so the convention holds everywhere else and the
 * three portraits are the only exceptions.
 *
 * So the map now covers every tier and `srcSetFor` reads the real width, falling
 * back to the conventional constants for anything not in it. Drift is reported
 * rather than fatal, because the map is the record of the truth and a hardcoded
 * descriptor that disagrees with the file is the bug this exists to prevent.
 *
 * Nothing is re-encoded and no bytes change — the manifest only tells the markup
 * the truth.
 *
 * Idempotent. Run: `node scripts/generate-image-widths.mjs`
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { join, dirname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const imagesDir = join(root, 'public', 'images')
const outFile = join(root, 'src', 'lib', 'image-tier-widths.ts')

/** Conventions `srcSetFor` falls back to for paths absent from the map. */
const SMALL_WIDTH = 800
const BASE_WIDTH = 1200

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) walk(p, acc)
    else if (entry.name.toLowerCase().endsWith('.avif')) acc.push(p)
  }
  return acc
}

/** Public URL path, e.g. `/images/hero/hero-homepage-lg.avif`. */
const publicPath = (file) => '/images/' + relative(imagesDir, file).split(sep).join('/')

const widths = []
const offConvention = []

for (const file of walk(imagesDir).sort()) {
  const { width } = await sharp(file).metadata()
  const name = file.split(sep).pop()
  const path = publicPath(file)
  widths.push([path, width])

  // Report anything that breaks the convention the constants describe. Not
  // fatal: these three portraits are square by design and are the reason the map
  // exists. A silent drift is the failure mode worth catching.
  const isSmall = /-sm\.avif$/i.test(name)
  const isLarge = /-lg\.avif$/i.test(name)
  const expected = isSmall ? SMALL_WIDTH : isLarge ? null : BASE_WIDTH
  if (expected !== null && width !== expected) {
    offConvention.push(`${path} is ${width}px, convention says ${expected}px`)
  }
}

const body = widths.map(([p, w]) => `  '${p}': ${w},`).join('\n')

const contents = `/**
 * Intrinsic pixel width of every AVIF in the library, by public path.
 *
 * GENERATED by \`scripts/generate-image-widths.mjs\` — do not edit by hand.
 * Run \`npm run images:widths\` after changing anything under \`public/images\`.
 *
 * Tiers have no single width. The large tier varies because
 * \`shrink-oversized-avif.mjs\` caps any AVIF over 400 KB at 2000px; the three
 * founder portraits vary because a square crop can only be as wide as its source
 * is tall. Emitting hardcoded descriptors mis-declared 13 of 19 large assets
 * before this map covered them.
 *
 * A plain data map keeps this module filesystem-free, so it stays safe to import
 * from client components.
 */
export const TIER_WIDTHS: Readonly<Record<string, number>> = {
${body}
}

/** Kept for callers that only need the large tier. */
export const LARGE_TIER_WIDTHS: Readonly<Record<string, number>> = Object.fromEntries(
  Object.entries(TIER_WIDTHS).filter(([p]) => /-lg\\.avif$/.test(p))
)
`

writeFileSync(outFile, contents)

const byWidth = widths.reduce((acc, [, w]) => ({ ...acc, [w]: (acc[w] ?? 0) + 1 }), {})
const summary = Object.entries(byWidth)
  .sort((a, b) => b[0] - a[0])
  .map(([w, n]) => `${w}px x${n}`)
  .join(', ')

console.log(`Recorded ${widths.length} files (${summary}).`)
console.log(`Wrote ${relative(root, outFile).split(sep).join('/')}`)

if (offConvention.length) {
  console.log('')
  console.log(`Off-convention widths (${offConvention.length}) — these are why the map exists:`)
  for (const d of offConvention) console.log(`  ${d}`)
}