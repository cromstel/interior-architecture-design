/**
 * Dev-time generator for the intrinsic width of every `-lg` image.
 *
 * `srcSetFor` emits width descriptors, and a descriptor has to equal the
 * file's true pixel width or the browser mis-selects candidates. The small and
 * base tiers are fixed by convention (800w and 1200w) and are asserted below,
 * but the large tier is deliberately *not* uniform: `shrink-oversized-avif.mjs`
 * caps any AVIF over 400 KB at 2000px, so `-lg` assets are 2400px unless the
 * texture-heavy ones were shrunk. A hardcoded `2000w` was therefore wrong for
 * 13 of the 19 large assets.
 *
 * This records the real widths so the descriptors are always accurate. Nothing
 * is re-encoded and no bytes change — the manifest only tells the markup the
 * truth.
 *
 * Idempotent. Run: `node scripts/generate-image-widths.mjs`
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { join, dirname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const imagesDir = join(root, 'public', 'images')
const outFile = join(root, 'src', 'lib', 'image-large-tiers.ts')

/** Fixed by `add-small-tier.mjs` and `fetch-images.mjs`; verified below. */
const SMALL_WIDTH = 800
const BASE_WIDTH = 1200

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) walk(p, acc)
    else if (entry.name.toLowerCase().endsWith('.avif')) acc.push(p)
  }
  return acc
}

/** Public URL path, e.g. `/images/hero/hero-homepage-lg.avif`. */
const publicPath = (file) => '/images/' + relative(imagesDir, file).split(sep).join('/')

const large = []
const drift = []

for (const file of walk(imagesDir).sort()) {
  const { width } = await sharp(file).metadata()
  const name = file.split(sep).pop()
  if (/-lg\.avif$/i.test(name)) {
    large.push([publicPath(file), width])
  } else if (/-sm\.avif$/i.test(name)) {
    if (width !== SMALL_WIDTH) drift.push(`${publicPath(file)} is ${width}px, expected ${SMALL_WIDTH}px`)
  } else if (width !== BASE_WIDTH) {
    drift.push(`${publicPath(file)} is ${width}px, expected ${BASE_WIDTH}px`)
  }
}

if (drift.length) {
  console.error('Tier widths drifted from the values srcSetFor assumes:')
  for (const d of drift) console.error('  ' + d)
  console.error('\nFix the pipeline, or update SMALL_WIDTH / BASE_WIDTH in src/lib/responsive-image.ts.')
  process.exit(1)
}

const body = large
  .map(([p, w]) => `  '${p}': ${w},`)
  .join('\n')

const contents = `/**
 * Intrinsic pixel width of every \`-lg\` image, by public path.
 *
 * GENERATED by \`scripts/generate-image-widths.mjs\` — do not edit by hand.
 * Run \`npm run images:widths\` after changing anything under \`public/images\`.
 *
 * The large tier has no single width: assets over 400 KB are capped at 2000px
 * by \`shrink-oversized-avif.mjs\`, the rest stay at 2400px. Emitting a single
 * hardcoded descriptor mis-declared 13 of 19 files. A plain data map keeps this
 * module filesystem-free, so it stays safe to import from client components.
 */
export const LARGE_TIER_WIDTHS: Readonly<Record<string, number>> = {
${body}
}
`

writeFileSync(outFile, contents)

const byWidth = large.reduce((acc, [, w]) => ({ ...acc, [w]: (acc[w] ?? 0) + 1 }), {})
const summary = Object.entries(byWidth)
  .sort((a, b) => b[0] - a[0])
  .map(([w, n]) => `${w}px x${n}`)
  .join(', ')

console.log(`Large tiers: ${large.length} files (${summary}).`)
console.log(`Wrote ${relative(root, outFile).split(sep).join('/')}`)
